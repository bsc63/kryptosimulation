import express from 'express';
import http from 'http';
import { createServer as createViteServer } from 'vite';
import { Block, Transaction, Participant } from './src/types/blockchain';
import {
  INITIAL_PARTICIPANTS,
  createGenesisBlock,
  createInitialBlock1,
  validateEntireChain,
} from './src/utils/crypto';
import { generateRandomStudentTransaction } from './src/utils/autoGenerator';
import { calculateBalances } from './src/utils/crypto';

const app = express();
app.use(express.json());

// In-Memory Server Blockchain State
let chain: Block[] = [];
let mempool: Transaction[] = [];
let participants: Participant[] = [...INITIAL_PARTICIPANTS];

// Connected SSE Clients for Real-Time LAN Broadcasts
interface SseClient {
  id: string;
  res: express.Response;
}
let sseClients: SseClient[] = [];

// Broadcast helper function
function broadcast(eventType: string, data: any) {
  const payload = `event: ${eventType}\ndata: ${JSON.stringify(data)}\n\n`;
  sseClients.forEach((client) => {
    try {
      client.res.write(payload);
    } catch {
      // client disconnected
    }
  });
}

// Initialize server blockchain
async function initServerBlockchain() {
  const genesis = await createGenesisBlock();
  const block1 = await createInitialBlock1(genesis);
  chain = [genesis, block1];

  mempool = [
    {
      id: 'tx-seed-1',
      senderId: 'sophie',
      senderName: 'Sophie',
      recipientId: 'jonas',
      recipientName: 'Jonas',
      amount: 3,
      purpose: 'Hausaufgaben-Zusammenfassung Physik',
      timestamp: Date.now() - 240000,
      isAutoGenerated: true,
    },
    {
      id: 'tx-seed-2',
      senderId: 'lukas',
      senderName: 'Lukas',
      recipientId: 'mia',
      recipientName: 'Mia',
      amount: 4,
      purpose: 'Gaming-Mauspad ausgeliehen',
      timestamp: Date.now() - 120000,
      isAutoGenerated: true,
    },
  ];

  console.log('✅ Server Blockchain initialized with Genesis + Block #1');
}

// API Routes
app.get('/api/state', (req, res) => {
  res.json({
    chain,
    mempool,
    participants,
    serverTime: Date.now(),
  });
});

app.post('/api/join', (req, res) => {
  const player: Participant = req.body;
  if (!player || !player.name) {
    return res.status(400).json({ error: 'Name erforderlich' });
  }

  // Check if player already exists
  const existingIndex = participants.findIndex((p) => p.id === player.id || p.name.toLowerCase() === player.name.toLowerCase());
  if (existingIndex >= 0) {
    participants[existingIndex] = { ...participants[existingIndex], ...player };
  } else {
    participants.push(player);
  }

  broadcast('participant_joined', { player, participants });
  res.json({ success: true, participant: player });
});

app.post('/api/transactions', (req, res) => {
  const tx: Transaction = req.body;
  if (!tx || !tx.senderId || !tx.recipientId || !tx.amount) {
    return res.status(400).json({ error: 'Ungültige Transaktionsdaten' });
  }

  // Add to mempool
  mempool.unshift(tx);
  broadcast('transaction_added', { transaction: tx, mempool });
  res.json({ success: true, transaction: tx });
});

app.post('/api/mine', async (req, res) => {
  const newBlock: Block = req.body;
  if (!newBlock || newBlock.index === undefined || !newBlock.hash) {
    return res.status(400).json({ error: 'Ungültige Blockdaten' });
  }

  // Validate chain with new block
  const testChain = [...chain, newBlock];
  const validation = await validateEntireChain(testChain);

  if (!validation.isValid) {
    return res.status(400).json({ error: 'Kryptografische Validierung fehlgeschlagen! Block ungültig.' });
  }

  // Append valid block
  chain = validation.validatedBlocks;

  // Clear mined transactions from mempool
  const minedTxIds = new Set(newBlock.transactions.map((t) => t.id));
  mempool = mempool.filter((t) => !minedTxIds.has(t.id));

  broadcast('block_mined', { block: newBlock, chain, mempool });
  res.json({ success: true, block: newBlock, chain, mempool });
});

app.post('/api/reset', async (req, res) => {
  await initServerBlockchain();
  broadcast('chain_reset', { chain, mempool, participants });
  res.json({ success: true });
});

// Server-Sent Events (SSE) Stream
app.get('/api/events', (req, res) => {
  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');
  res.flushHeaders();

  const clientId = `client-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  sseClients.push({ id: clientId, res });

  // Send initial state immediately
  res.write(`event: init\ndata: ${JSON.stringify({ chain, mempool, participants })}\n\n`);

  // Heartbeat ping every 20 seconds
  const pingInterval = setInterval(() => {
    try {
      res.write(': ping\n\n');
    } catch {
      clearInterval(pingInterval);
    }
  }, 20000);

  req.on('close', () => {
    clearInterval(pingInterval);
    sseClients = sseClients.filter((c) => c.id !== clientId);
  });
});

// Periodic background bot transactions on server (every 20 to 35s)
setInterval(() => {
  if (participants.length > 0) {
    const balances = calculateBalances(participants, chain, mempool);
    const autoTx = generateRandomStudentTransaction(participants, balances);
    if (autoTx) {
      mempool.unshift(autoTx);
      broadcast('transaction_added', { transaction: autoTx, mempool });
    }
  }
}, 24000);

async function startServer() {
  await initServerBlockchain();

  const server = http.createServer(app);
  const PORT = Number(process.env.PORT) || 3000;

  // In dev environment, mount Vite middlewares
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static('docs'));
    app.use(express.static('dist'));
  }

  server.listen(PORT, '0.0.0.0', () => {
    console.log(`====================================================`);
    console.log(`🎓 KryptoKette Schul-Netzwerk-Server läuft auf Port ${PORT}`);
    console.log(`📡 Lokale IP für Mitschüler im LAN: http://0.0.0.0:${PORT}`);
    console.log(`====================================================`);
  });
}

startServer();
