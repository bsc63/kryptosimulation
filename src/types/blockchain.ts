export interface Transaction {
  id: string;
  senderId: string;
  senderName: string;
  recipientId: string;
  recipientName: string;
  amount: number;
  purpose: string;
  timestamp: number;
  isCoinbase?: boolean;
  isAutoGenerated?: boolean;
}

export interface Block {
  index: number;
  timestamp: number;
  transactions: Transaction[];
  previousHash: string;
  hash: string;
  nonce: number;
  difficulty: number;
  minerId: string;
  minerName: string;
  isGenesis?: boolean;
  isValid?: boolean;
  tampered?: boolean;
  tamperOriginalHash?: string;
  miningDurationSeconds?: number;
  hashesCalculated?: number;
  blockType?: 'manual' | 'network';
}

export interface Participant {
  id: string;
  name: string;
  avatar: string;
  color: string;
  grade: string;
  role: string;
  description: string;
  initialBalance: number;
  isHumanPlayer?: boolean;
  isCurrentUser?: boolean;
  joinedAt?: number;
}

export interface MiningReceipt {
  blockIndex: number;
  minerName: string;
  minerId: string;
  minerAvatar: string;
  rewardAmount: number;
  nonce: number;
  hash: string;
  difficulty: number;
  durationSeconds: number;
  attempts: number;
  timestamp: number;
  transactionCount: number;
  transactions: Transaction[];
}

export interface Mission {
  id: string;
  title: string;
  description: string;
  hint: string;
  completed: boolean;
  actionText: string;
}

export interface GlossaryTerm {
  term: string;
  simpleName: string;
  explanation: string;
  everydayAnalogy: string;
  iconName: string;
}
