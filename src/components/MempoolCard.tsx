import React from 'react';
import { Transaction } from '../types/blockchain';
import {
  Inbox,
  Cpu,
  Send,
  Sparkles,
  ArrowRight,
  Clock,
  PlusCircle,
  Radio,
  Pause,
  Play,
  Zap,
} from 'lucide-react';

interface MempoolCardProps {
  mempool: Transaction[];
  onOpenMining: () => void;
  onOpenTransfer: () => void;
  onAddQuickTransaction: () => void;
  isAutoGenerating: boolean;
  onToggleAutoGenerating: () => void;
}

export const MempoolCard: React.FC<MempoolCardProps> = ({
  mempool,
  onOpenMining,
  onOpenTransfer,
  onAddQuickTransaction,
  isAutoGenerating,
  onToggleAutoGenerating,
}) => {
  const hasAutoTx = mempool.some((t) => t.isAutoGenerated);
  const isMempoolEmpty = mempool.length === 0;

  return (
    <div className="bg-white rounded-xl border border-slate-200/80 p-5 shadow-xs flex flex-col justify-between">
      <div>
        {/* Card Header */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 mb-3">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-sky-100 text-sky-700 flex items-center justify-center">
              <Inbox className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-slate-900 tracking-tight flex items-center gap-2">
                <span>Mempool (Warteraum)</span>
                <span className={`font-mono text-xs px-2 py-0.5 rounded-full font-semibold ${
                  isMempoolEmpty ? 'bg-slate-100 text-slate-500' : 'bg-sky-50 text-sky-700'
                }`}>
                  {mempool.length} wartend
                </span>
              </h3>
            </div>
          </div>

          {/* Quick Transaction Button */}
          <button
            onClick={onAddQuickTransaction}
            title="Jetzt sofort einen Schüler-Auftrag ins Netzwerk senden"
            className="text-xs text-sky-700 hover:text-sky-800 font-medium flex items-center gap-1 hover:underline"
          >
            <PlusCircle className="w-3.5 h-3.5" />
            <span className="hidden sm:inline">Neuer Auftrag</span>
          </button>
        </div>

        {/* Live Network Simulation Indicator */}
        <div className="mb-3 px-3 py-2 bg-slate-50 border border-slate-200/80 rounded-lg flex items-center justify-between text-xs">
          <div className="flex items-center gap-2">
            <Radio className={`w-3.5 h-3.5 ${isAutoGenerating ? 'text-emerald-500 animate-pulse' : 'text-slate-400'}`} />
            <span className="text-[11px] font-medium text-slate-700">
              {isAutoGenerating
                ? 'Schul-Netzwerk generiert Aufträge (~15–30s)'
                : 'Automatische Aufträge pausiert'}
            </span>
          </div>

          <button
            onClick={onToggleAutoGenerating}
            className="p-1 text-slate-500 hover:text-slate-800 rounded transition-colors"
            title={isAutoGenerating ? 'Automatische Aufträge anhalten' : 'Automatische Aufträge starten'}
          >
            {isAutoGenerating ? (
              <Pause className="w-3.5 h-3.5" />
            ) : (
              <Play className="w-3.5 h-3.5 text-emerald-600" />
            )}
          </button>
        </div>

        <p className="text-xs text-slate-500 mb-3">
          Hier sammeln sich Überweisungen der Schüler. Sie werden erst gültig, wenn ein Miner sie in einen Block rechnet.
        </p>

        {/* Transaction list */}
        {isMempoolEmpty ? (
          <div className="border border-dashed border-slate-200 rounded-lg p-5 text-center text-xs text-slate-500 bg-slate-50/50 space-y-2">
            <Inbox className="w-6 h-6 text-slate-400 mx-auto" />
            <p className="font-medium text-slate-700">Warteraum ist aktuell leer</p>
            <p className="text-[11px] text-slate-500 max-w-xs mx-auto">
              Ein Block kann erst geschürft werden, wenn Transaktionen vorliegen. Warte auf das Schul-Netzwerk oder sende selbst Geld!
            </p>
            <div className="pt-1 flex items-center justify-center gap-2">
              <button
                onClick={onOpenTransfer}
                className="inline-flex items-center gap-1 px-3 py-1.5 text-xs font-semibold text-sky-700 bg-sky-50 hover:bg-sky-100 rounded-md transition-colors"
              >
                <Send className="w-3 h-3" />
                Selbst überweisen
              </button>
              <button
                onClick={onAddQuickTransaction}
                className="inline-flex items-center gap-1 px-3 py-1.5 text-xs font-medium text-slate-600 bg-white border border-slate-200 hover:bg-slate-50 rounded-md transition-colors"
              >
                <PlusCircle className="w-3 h-3" />
                Auftrag generieren
              </button>
            </div>
          </div>
        ) : (
          <div className="space-y-2 max-h-56 overflow-y-auto pr-1">
            {mempool.map((tx) => (
              <div
                key={`mem-${tx.id}`}
                className={`p-2.5 rounded-lg border text-xs transition-colors ${
                  tx.isAutoGenerated
                    ? 'border-indigo-100 bg-indigo-50/30 hover:bg-indigo-50/60'
                    : 'border-slate-200 bg-slate-50/60 hover:bg-white'
                }`}
              >
                <div className="flex items-center justify-between font-semibold">
                  <div className="flex items-center gap-1.5 text-slate-800 truncate">
                    <span>{tx.senderName}</span>
                    <ArrowRight className="w-3 h-3 text-slate-400 shrink-0" />
                    <span>{tx.recipientName}</span>
                  </div>
                  <span className="font-mono tabular-nums text-slate-900 font-bold shrink-0">
                    {tx.amount} EDC
                  </span>
                </div>
                <div className="flex items-center justify-between mt-1 text-[11px] text-slate-500">
                  <span className="truncate italic">"{tx.purpose}"</span>
                  <span className="flex items-center gap-1 text-[10px] text-amber-600 font-medium shrink-0 ml-2">
                    <Clock className="w-3 h-3" />
                    wartet
                  </span>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>

      {/* Action Footer: Mining Button disabled when Mempool is empty */}
      <div className="pt-3 mt-3 border-t border-slate-100 flex flex-col gap-1.5">
        <button
          onClick={onOpenMining}
          disabled={isMempoolEmpty}
          className={`w-full flex items-center justify-center gap-2 py-2.5 px-3 text-xs font-semibold rounded-lg transition-all ${
            isMempoolEmpty
              ? 'bg-slate-100 text-slate-400 border border-slate-200 cursor-not-allowed'
              : hasAutoTx
              ? 'bg-amber-600 hover:bg-amber-700 text-white shadow-xs font-bold'
              : 'bg-sky-600 hover:bg-sky-700 text-white shadow-xs font-bold'
          }`}
        >
          <Cpu className="w-4 h-4" />
          <span>
            {isMempoolEmpty
              ? 'Kein Schürfen möglich (Warteraum leer)'
              : hasAutoTx
              ? `Netzwerk-Block schürfen (${mempool.length} Aufträge · ca. 25–45s Aufwand)`
              : `Express-Block schürfen (${mempool.length} Auftrag)`}
          </span>
        </button>

        {!isMempoolEmpty && hasAutoTx && (
          <div className="text-[10px] text-amber-700 text-center font-medium flex items-center justify-center gap-1">
            <Zap className="w-3 h-3 text-amber-500" />
            <span>Spannender Proof-of-Work: Tausende Hashes werden berechnet!</span>
          </div>
        )}
      </div>
    </div>
  );
};
