/**
 * Generates an organic, irregular transaction between students.
 */
export function generateRandomStudentTransaction(
  participants: Participant[],
  balances: Record<string, { confirmed: number; pendingChange: number }>
): Transaction | null {
  if (participants.length < 2) return null;

  // Filter participants who have at least 3 EDC to spend
  const validSenders = participants.filter((p) => {
    const bal = balances[p.id];
    const available = (bal?.confirmed ?? p.initialBalance) + (bal?.pendingChange ?? 0);
    return available >= 3;
  });

  if (validSenders.length === 0) return null;

  // Pick random sender
  const sender = validSenders[Math.floor(Math.random() * validSenders.length)];
  const senderBalance = (balances[sender.id]?.confirmed ?? sender.initialBalance) + (balances[sender.id]?.pendingChange ?? 0);

  // Pick random recipient different from sender
  const possibleRecipients = participants.filter((p) => p.id !== sender.id);
  const recipient = possibleRecipients[Math.floor(Math.random() * possibleRecipients.length)];

  // Pick a random purpose whose amount fits sender balance
  const fittingPurposes = SCHOOL_PURPOSES.filter((p) => p.amount <= senderBalance);
  const purpose = fittingPurposes.length > 0
    ? fittingPurposes[Math.floor(Math.random() * fittingPurposes.length)]
    : { text: 'Taschengeld-Überweisung', amount: Math.min(2, Math.max(1, senderBalance)) };

  return {
    id: `tx-auto-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    senderId: sender.id,
    senderName: sender.name,
    recipientId: recipient.id,
    recipientName: recipient.name,
    amount: purpose.amount,
    purpose: purpose.text,
    timestamp: Date.now(),
    isCoinbase: false,
    isAutoGenerated: true,
  };
}

/**
 * Computes an irregular next interval in milliseconds (e.g. 15 to 30 seconds).
 */
export function getNextIrregularIntervalMs(): number {
  // Between 14,000ms and 28,000ms (14s to 28s)
  return Math.floor(14000 + Math.random() * 14000);
}
